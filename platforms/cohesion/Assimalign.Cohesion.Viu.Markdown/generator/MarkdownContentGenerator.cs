using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Threading;

using Assimalign.Cohesion.Viu.Markdown.Internal;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;

namespace Assimalign.Cohesion.Viu.Markdown.Generator;

/// <summary>Incrementally extracts Markdown metadata and emits a deterministic declarative catalog.</summary>
[Generator(LanguageNames.CSharp)]
public sealed class MarkdownContentGenerator : IIncrementalGenerator
{
    /// <summary>Registers content-file inputs and compiler-visible options without loading runtime assemblies.</summary>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<ExtractedContent?> files = context.AdditionalTextsProvider
            .Combine(context.AnalyzerConfigOptionsProvider)
            .Select(static (pair, cancellationToken) => ReadFile(pair.Left, pair.Right, cancellationToken))
            .Select(static (file, _) => file is null ? null : Extract(file));
        IncrementalValueProvider<string> generatedNamespace = context.AnalyzerConfigOptionsProvider
            .Select(static (provider, _) => GetOption(provider.GlobalOptions, "ViuMarkdownGeneratedNamespace", "Assimalign.Cohesion.Viu.Markdown.Generated"));
        context.RegisterSourceOutput(files.Collect().Combine(generatedNamespace),
            static (productionContext, pair) => Generate(productionContext, pair.Left, pair.Right));
    }

    private static ContentFile? ReadFile(AdditionalText file, AnalyzerConfigOptionsProvider options,
        CancellationToken cancellationToken)
    {
        AnalyzerConfigOptions metadata = options.GetOptions(file);
        if (!metadata.TryGetValue("build_metadata.AdditionalFiles.ViuMarkdownContent", out string? enabled) ||
            !string.Equals(enabled, "true", StringComparison.OrdinalIgnoreCase))
        {
            return null;
        }
        metadata.TryGetValue("build_metadata.AdditionalFiles.ViuMarkdownSourceRelativePath", out string? relativePath);
        // The build computes the packaged asset name (hashed by default) so the catalog and the
        // package layout agree; an absent value keeps the source-relative path as the asset name.
        metadata.TryGetValue("build_metadata.AdditionalFiles.ViuMarkdownAssetName", out string? assetName);
        SourceText? text = file.GetText(cancellationToken);
        return text is null ? null : new ContentFile(file.Path, relativePath ?? file.Path, text.ToString(),
            GetOption(options.GlobalOptions, "ViuMarkdownContentPrefix", "docs/"),
            GetOption(options.GlobalOptions, "ViuMarkdownRouteBase", "/"),
            string.IsNullOrWhiteSpace(assetName) ? null : assetName);
    }

    private static ExtractedContent Extract(ContentFile file)
    {
        List<ExtractionDiagnostic> diagnostics = new List<ExtractionDiagnostic>();
        ExtractedPage page = ContentExtraction.Extract(file.RelativePath, file.Text, file.Prefix, file.RouteBase, diagnostics.Add, file.AssetName);
        return new ExtractedContent(file, page, diagnostics);
    }

    private static void Generate(SourceProductionContext context, ImmutableArray<ExtractedContent?> input,
        string generatedNamespace)
    {
        if (generatedNamespace.Split('.').Any(segment => !SyntaxFacts.IsValidIdentifier(segment)))
        {
            Report(context, new ExtractionDiagnostic("VIUMD005", "", "The generated namespace is not a valid C# namespace.", true), input);
            return;
        }
        List<ExtractedPage> pages = new List<ExtractedPage>();
        bool hasErrors = false;
        void ReportDiagnostic(ExtractionDiagnostic diagnostic)
        {
            hasErrors |= diagnostic.IsError;
            Report(context, diagnostic, input);
        }
        foreach (ExtractedContent content in input.Where(file => file is not null).Cast<ExtractedContent>()
            .OrderBy(content => content.File.RelativePath, StringComparer.Ordinal))
        {
            context.CancellationToken.ThrowIfCancellationRequested();
            pages.Add(content.Page);
            foreach (ExtractionDiagnostic diagnostic in content.Diagnostics)
            {
                ReportDiagnostic(diagnostic);
            }
        }
        ExtractedSection root = ContentExtraction.Arrange(pages, ReportDiagnostic);
        if (hasErrors)
        {
            return;
        }

        StringBuilder source = new StringBuilder();
        source.Append("// <auto-generated/>\n#nullable enable\nnamespace ").Append(generatedNamespace).Append(";\n\n");
        source.Append("/// <summary>Provides the immutable Markdown catalog extracted at build time.</summary>\n");
        source.Append("public static class GeneratedMarkdownContent\n{\n");
        source.Append("    /// <summary>Gets the catalog without reading or parsing Markdown at runtime.</summary>\n");
        source.Append("    public static global::Assimalign.Cohesion.Viu.Markdown.MarkdownContentCatalog Catalog { get; } = new(\n");
        source.Append("        new global::Assimalign.Cohesion.Viu.Markdown.MarkdownSection[]\n        {\n");
        WriteSection(source, root, 12);
        source.Append("        });\n}\n");
        context.AddSource("GeneratedMarkdownContent.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
    }

    private static void WriteSection(StringBuilder source, ExtractedSection section, int indentation)
    {
        string indent = new string(' ', indentation);
        source.Append(indent).Append("new global::Assimalign.Cohesion.Viu.Markdown.MarkdownSection(\n")
            .Append(indent).Append("    ").Append(Literal(section.Title)).Append(", ").Append(Literal(section.Path)).Append(",\n")
            .Append(indent).Append("    new global::Assimalign.Cohesion.Viu.Markdown.MarkdownPageEntry[]\n")
            .Append(indent).Append("    {\n");
        foreach (ExtractedPage page in section.Pages)
        {
            source.Append(indent).Append("        new(").Append(Literal(page.RoutePath)).Append(", ")
                .Append(Literal(page.AssetPath)).Append(", ").Append(Literal(page.Title)).Append(", ")
                .Append(Literal(page.Description)).Append(", ").Append(page.Status is null ? "null" : Literal(page.Status)).Append(", ")
                .Append(Literal(page.SourceRelativePath)).Append(", ").Append(page.Order).Append("),\n");
        }
        source.Append(indent).Append("    },\n").Append(indent)
            .Append("    new global::Assimalign.Cohesion.Viu.Markdown.MarkdownSection[]\n")
            .Append(indent).Append("    {\n");
        foreach (ExtractedSection child in section.Sections)
        {
            WriteSection(source, child, indentation + 8);
        }
        source.Append(indent).Append("    }, ").Append(section.Order).Append("),\n");
    }

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, true);

    private static string GetOption(AnalyzerConfigOptions options, string name, string fallback)
        => options.TryGetValue("build_property." + name, out string? value) && value.Length > 0 ? value : fallback;

    private static void Report(SourceProductionContext context, ExtractionDiagnostic diagnostic,
        ImmutableArray<ExtractedContent?> files)
    {
        ContentFile? file = files.FirstOrDefault(candidate => candidate?.File.RelativePath.Replace('\\', '/') == diagnostic.Path)?.File;
        Location location = file is null ? Location.None : Location.Create(file.Path,
            new TextSpan(0, 0), new LinePositionSpan(new LinePosition(0, 0), new LinePosition(0, 0)));
        DiagnosticDescriptor descriptor = new DiagnosticDescriptor(diagnostic.Identifier,
            diagnostic.IsError ? "Invalid Markdown content catalog" : "Markdown content convention",
            "{0}", "Viu.Markdown", diagnostic.IsError ? DiagnosticSeverity.Error : DiagnosticSeverity.Warning, true);
        context.ReportDiagnostic(Diagnostic.Create(descriptor, location, diagnostic.Message));
    }

    private sealed class ContentFile : IEquatable<ContentFile>
    {
        internal ContentFile(string path, string relativePath, string text, string prefix, string routeBase,
            string? assetName = null)
        {
            Path = path;
            RelativePath = relativePath;
            Text = text;
            Prefix = prefix;
            RouteBase = routeBase;
            AssetName = assetName;
        }

        internal string Path { get; }
        internal string RelativePath { get; }
        internal string Text { get; }
        internal string Prefix { get; }
        internal string RouteBase { get; }
        internal string? AssetName { get; }

        public bool Equals(ContentFile? other)
            => other is not null && Path == other.Path && RelativePath == other.RelativePath && Text == other.Text &&
                Prefix == other.Prefix && RouteBase == other.RouteBase && AssetName == other.AssetName;
        public override bool Equals(object? other) => other is ContentFile file && Equals(file);
        public override int GetHashCode() => Path.GetHashCode();
    }

    private sealed class ExtractedContent(ContentFile file, ExtractedPage page, List<ExtractionDiagnostic> diagnostics)
        : IEquatable<ExtractedContent>
    {
        internal ContentFile File { get; } = file;
        internal ExtractedPage Page { get; } = page;
        internal IReadOnlyList<ExtractionDiagnostic> Diagnostics { get; } = diagnostics.AsReadOnly();

        public bool Equals(ExtractedContent? other) => other is not null && File.Equals(other.File);
        public override bool Equals(object? other) => other is ExtractedContent content && Equals(content);
        public override int GetHashCode() => File.GetHashCode();
    }
}
