using System;
using System.Collections.Generic;
using System.Text;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace Assimalign.Cohesion.Viu.Server.Generator;

/// <summary>Publishes Viu's compiler-known catalogs from a Cohesion Web executable.</summary>
/// <remarks>Consumes CMP-36 assembly attributes; it never discovers components or parses templates.</remarks>
[Generator]
public sealed class ViuServerCatalogGenerator : IIncrementalGenerator
{
    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValueProvider<bool?> enabled = context.AnalyzerConfigOptionsProvider.Select(
            static (provider, _) => provider.GlobalOptions.TryGetValue(
                "build_property.ViuAutoRegisterGeneratedCatalogs", out string? value) && !string.IsNullOrWhiteSpace(value)
                    ? (bool?)string.Equals(value, "true", StringComparison.OrdinalIgnoreCase)
                    : null);
        context.RegisterSourceOutput(context.CompilationProvider.Combine(enabled), static (output, input) =>
        {
            Compilation compilation = input.Left;
            bool aggregate = input.Right ?? compilation.Options.OutputKind is
                OutputKind.ConsoleApplication or OutputKind.WindowsApplication;
            if (!aggregate) { return; }

            List<IAssemblySymbol> assemblies = [compilation.Assembly, .. compilation.SourceModule.ReferencedAssemblySymbols];
            assemblies.Sort(static (left, right) => StringComparer.Ordinal.Compare(
                left.Identity.ToString(), right.Identity.ToString()));
            StringBuilder registrations = new();
            foreach (IAssemblySymbol assembly in assemblies)
            {
                output.CancellationToken.ThrowIfCancellationRequested();
                foreach (AttributeData attribute in assembly.GetAttributes())
                {
                    string? registry = attribute.AttributeClass?.ToDisplayString() switch
                    {
                        "Assimalign.Viu.Components.ComponentCatalogAttribute" =>
                            "global::Assimalign.Viu.Components.GeneratedComponentCatalogs",
                        "Assimalign.Viu.ServerRenderer.ServerRenderCatalogAttribute" =>
                            "global::Assimalign.Viu.ServerRenderer.GeneratedServerRenderCatalogs",
                        _ => null,
                    };
                    if (registry is null || attribute.ConstructorArguments.Length != 1
                        || attribute.ConstructorArguments[0].Value is not INamedTypeSymbol catalog)
                    {
                        continue;
                    }
                    registrations.Append("        ").Append(registry).Append(".Register(")
                        .Append(SymbolDisplay.FormatLiteral(assembly.Identity.ToString(), quote: true)).Append(", ")
                        .Append(catalog.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))
                        .AppendLine(".Register);");
                }
            }
            if (registrations.Length == 0) { return; }

            string source = "// <auto-generated/>\n" +
                "namespace Assimalign.Cohesion.Viu.Generated;\n" +
                "internal static class WebCatalogPublication\n{\n" +
                "    [global::System.Runtime.CompilerServices.ModuleInitializer]\n" +
                "    internal static void Register()\n    {\n" + registrations + "    }\n}\n";
            output.AddSource("Cohesion.Viu.WebCatalogs.g.cs", SourceText.From(source, Encoding.UTF8));
        });
    }
}
